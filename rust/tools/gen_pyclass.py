"""Write `pyclass.rs`: CPython's `str` character classes as Rust tables

The Python reference matches `\\d`, `\\s` and `\\w` with CPython's own Unicode
database (3.12, Unicode 15.0), which differs from the Rust regex crates' tables
(newer Unicode, `\\s` without U+001C..U+001F, `\\w` with combining marks). The
native post-processing builds its patterns from these tables instead.

Usage: python -I gen_pyclass.py OUT.rs
"""

import re
import sys
import unicodedata


def ranges(pred):
    out = []
    start = None
    for c in range(0x110000 + 1):
        hit = c < 0x110000 and pred(c)
        if hit and start is None:
            start = c
        elif not hit and start is not None:
            out.append((start, c - 1))
            start = None
    return out


def table(name, doc, rs):
    body = "\n".join(f"    (0x{a:04X}, 0x{b:04X})," for a, b in rs)
    return f"/// {doc}\npub const {name}: &[(u32, u32)] = &[\n{body}\n];\n"


def is_surrogate(c):
    return 0xD800 <= c <= 0xDFFF


def main():
    out = sys.argv[1]
    word = ranges(lambda c: not is_surrogate(c) and re.fullmatch(r"\w", chr(c)) is not None)
    digit = ranges(lambda c: not is_surrogate(c) and re.fullmatch(r"\d", chr(c)) is not None)
    space = ranges(lambda c: not is_surrogate(c) and re.fullmatch(r"\s", chr(c)) is not None)
    # every `\d` code point with its decimal value, as the first code point of each run of ten
    zeros = sorted({c - unicodedata.decimal(chr(c)) for a, b in digit for c in range(a, b + 1)})
    src = [
        "//! CPython `str` character classes, generated by `rust/tools/gen_pyclass.py`",
        f"//! from Python {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}); do not edit",
        "",
        table("WORD", "Code points CPython's `\\w` matches (`isalnum()` or `_`)", word),
        table("DIGIT", "Code points CPython's `\\d` matches (category Nd)", digit),
        table("SPACE", "Code points CPython's `\\s` matches (`isspace()`)", space),
        "/// First code point (value 0) of each run of ten decimal digits",
        "pub const DIGIT_ZEROS: &[u32] = &[" + ", ".join(f"0x{z:04X}" for z in zeros) + "];",
        "",
    ]
    with open(out, "w") as fh:
        fh.write("\n".join(src))


if __name__ == "__main__":
    main()
